# onfig/settings.py

# Contains configuration.

# For example:

# RabbitMQ host
# RabbitMQ port
# RabbitMQ username
# RabbitMQ password
# Queue names
# Model paths

# Your .env could contain:

# RABBITMQ_HOST=...
# RABBITMQ_PORT=5672
# RABBITMQ_USERNAME=...
# RABBITMQ_PASSWORD=...

# ML_JOB_QUEUE=...
# ML_RESULT_QUEUE=...

# And settings.py reads these values.